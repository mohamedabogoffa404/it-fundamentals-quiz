interface RawMcq {
  id: number;
  topic: QuestionTopic;
  prompt: string;
  options: [string, string, string, string];
  correctIndex: 0 | 1 | 2 | 3;
  explanation: string;
}

/**
 * Deterministically permutes the 4 options of an MCQ based on its question ID
 * so correct answers are evenly distributed across أ / ب / ج / د rather than
 * clustering on the first option, while preserving exact option texts & correctness.
 */
function buildMcq(raw: RawMcq): MultipleChoiceQuestion {
  const permutations: [number, number, number, number][] = [
    [0, 1, 2, 3],
    [1, 0, 3, 2],
    [2, 3, 0, 1],
    [3, 2, 1, 0],
    [1, 2, 3, 0],
    [2, 0, 1, 3],
    [3, 1, 0, 2],
    [0, 3, 2, 1],
  ];
  const perm = permutations[(raw.id * 3 + 1) % permutations.length];
  const shuffledOptions: [string, string, string, string] = [
    raw.options[perm[0]],
    raw.options[perm[1]],
    raw.options[perm[2]],
    raw.options[perm[3]],
  ];
  const newCorrectIndex = perm.indexOf(raw.correctIndex) as 0 | 1 | 2 | 3;

  return {
    id: raw.id,
    section: 'multiple_choice',
    topic: raw.topic,
    prompt: raw.prompt,
    options: shuffledOptions,
    correctIndex: newCorrectIndex,
    explanation: raw.explanation,
  };
}

